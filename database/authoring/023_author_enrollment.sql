create or replace function public.author_enrollment(p_user uuid,p_action text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s authoring.enrollment_settings; a authoring.author_identity_attempts; c authoring.author_rights_consents;
 d authoring.enrollment_documents; privacy authoring.enrollment_documents; person uuid; aid bigint; result jsonb;
 stamp timestamptz:=clock_timestamp();
begin
 -- One lock order for start/verify/complete/cancel, including concurrent callbacks.
 perform 1 from auth.users u where id=p_user and email_confirmed_at is not null and email is not null
  and is_anonymous is not true and (to_jsonb(u)->>'deleted_at') is null
  and (banned_until is null or banned_until<=now()) for update;
 if not found then return jsonb_build_object('error','INVALID_SESSION','status',401); end if;
 if exists(select 1 from public.authors where auth_user_id=p_user and status::text is distinct from 'APPROVED')
 or exists(select 1 from public.readers where auth_user_id=p_user and status::text is distinct from 'ACTIVE')
 or exists(select 1 from public.admin_users where auth_user_id=p_user and is_active is distinct from true) then
  return jsonb_build_object('error','ACCOUNT_INACTIVE','status',403); end if;
 if jsonb_typeof(p_data) is distinct from 'object' then return jsonb_build_object('error','INVALID_REQUEST','status',400); end if;
 select * into s from authoring.enrollment_settings where singleton for share;
 if p_action='status' then
  select * into a from authoring.author_identity_attempts where auth_user_id=p_user order by created_at desc,id desc limit 1;
  return jsonb_build_object('completed',exists(select 1 from authoring.author_identity_accounts where auth_user_id=p_user),
   'existingAuthor',exists(select 1 from public.authors where auth_user_id=p_user),
   'attempt',case when a.id is not null then authoring.enrollment_attempt_json(a) end);
 end if;
 if s.enabled is distinct from true then return jsonb_build_object('error','AUTHOR_ENROLLMENT_NOT_READY','status',503); end if;
 if p_action='start' then
  if p_data->'rightsAccepted' is distinct from 'true'::jsonb or p_data->'privacyAccepted' is distinct from 'true'::jsonb
   or coalesce(p_data->>'rightsBasis','') not in ('OWN','LICENSED') then
   return jsonb_build_object('error','AUTHOR_CONSENT_REQUIRED','status',400); end if;
  select * into d from authoring.enrollment_documents where id=case p_data->>'rightsBasis' when 'OWN' then 'copyright-own' else 'copyright-licensed' end;
  select * into privacy from authoring.enrollment_documents where id='identity-privacy';
  if d.id is null or privacy.id is null or p_data->>'documentVersion' is distinct from d.version
   or p_data->>'documentHash' is distinct from d.hash or p_data->>'privacyVersion' is distinct from privacy.version
   or p_data->>'privacyHash' is distinct from privacy.hash then
   return jsonb_build_object('error','AUTHOR_CONSENT_STALE','status',409); end if;
  select * into a from authoring.author_identity_attempts where auth_user_id=p_user and request_key=(p_data->>'requestKey')::uuid;
  if found then
   select * into c from authoring.author_rights_consents where attempt_id=a.id;
   if c.document_hash is distinct from d.hash or c.privacy_hash is distinct from privacy.hash then
    return jsonb_build_object('error','CONFLICT','status',409); end if;
   return jsonb_build_object('attempt',authoring.enrollment_attempt_json(a));
  end if;
  if (select count(*) from authoring.author_identity_attempts where auth_user_id=p_user and created_at>stamp-interval '1 day')>=5 then
   return jsonb_build_object('error','RATE_LIMITED','status',429); end if;
  update authoring.author_identity_attempts set status='CANCELLED' where auth_user_id=p_user and status in ('PENDING','VERIFIED');
  insert into authoring.author_identity_attempts(id,auth_user_id,request_key,store_id,channel_key,mode,pg_provider,identifier_type,key_version,expires_at)
   values('ae_'||replace(gen_random_uuid()::text,'-',''),p_user,(p_data->>'requestKey')::uuid,s.store_id,s.channel_key,s.mode,
    s.pg_provider,s.identifier_type,s.key_version,stamp+interval '10 minutes') returning * into a;
  insert into authoring.author_rights_consents(attempt_id,auth_user_id,rights_basis,document_id,document_version,document_hash,privacy_id,privacy_version,privacy_hash)
   values(a.id,p_user,p_data->>'rightsBasis',d.id,d.version,d.hash,privacy.id,privacy.version,privacy.hash);
  return jsonb_build_object('attempt',authoring.enrollment_attempt_json(a));
 end if;
 select * into a from authoring.author_identity_attempts where id=p_data->>'attemptId' and auth_user_id=p_user for update;
 if not found then return jsonb_build_object('error','IDENTITY_ATTEMPT_INVALID','status',404); end if;
 if p_action='get' then return jsonb_build_object('attempt',authoring.enrollment_attempt_json(a)); end if;
 if a.status='CONSUMED' and p_action in ('verify','complete') then
  return jsonb_build_object('completed',true,'attempt',authoring.enrollment_attempt_json(a)); end if;
 if p_action='cancel' then
  update authoring.author_identity_attempts set status='CANCELLED' where id=a.id and status in ('PENDING','VERIFIED');
  return jsonb_build_object('cancelled',true);
 end if;
 if a.expires_at<=stamp then
  update authoring.author_identity_attempts set status='EXPIRED',fingerprint=null where id=a.id;
  return jsonb_build_object('error','IDENTITY_ATTEMPT_EXPIRED','status',409); end if;
 if a.status not in ('PENDING','VERIFIED') then return jsonb_build_object('error','IDENTITY_ATTEMPT_INVALID','status',409); end if;
 if (a.store_id,a.channel_key,a.mode,a.pg_provider,a.identifier_type,a.key_version) is distinct from
  (s.store_id,s.channel_key,s.mode,s.pg_provider,s.identifier_type,s.key_version) then
  return jsonb_build_object('error','IDENTITY_CONFIGURATION_REQUIRED','status',503); end if;
 if p_action='verify' then
  if a.status='VERIFIED' then return jsonb_build_object('attempt',authoring.enrollment_attempt_json(a)); end if;
  if coalesce(p_data->>'fingerprint','') !~ '^[a-f0-9]{64}$' or p_data->>'verifiedAt' is null
   or (p_data->>'verifiedAt')::timestamptz<a.created_at or (p_data->>'verifiedAt')::timestamptz>least(stamp+interval '1 minute',a.expires_at) then
   return jsonb_build_object('error','IDENTITY_NOT_VERIFIED','status',400); end if;
  update authoring.author_identity_attempts set status='VERIFIED',fingerprint=p_data->>'fingerprint',verified_at=(p_data->>'verifiedAt')::timestamptz
   where id=a.id returning * into a;
  return jsonb_build_object('attempt',authoring.enrollment_attempt_json(a));
 end if;
 if p_action<>'complete' then return jsonb_build_object('error','INVALID_ACTION','status',400); end if;
 if a.status<>'VERIFIED' then return jsonb_build_object('error','AUTHOR_IDENTITY_REQUIRED','status',403); end if;
 if a.mode<>'LIVE' then return jsonb_build_object('error','TEST_IDENTITY_NOT_ACCEPTED','status',403); end if;
 select * into c from authoring.author_rights_consents where attempt_id=a.id and auth_user_id=p_user;
 if not found or not exists(select 1 from authoring.enrollment_documents where id=c.document_id and version=c.document_version and hash=c.document_hash)
  or not exists(select 1 from authoring.enrollment_documents where id=c.privacy_id and version=c.privacy_version and hash=c.privacy_hash) then
  return jsonb_build_object('error','AUTHOR_CONSENT_STALE','status',409); end if;
 if exists(select 1 from authoring.author_identity_accounts where auth_user_id=p_user) then
  return jsonb_build_object('error','AUTHOR_ALREADY_VERIFIED','status',409); end if;
 result:=authoring.create_confirmed_profile(p_user,'author',p_data->>'displayName');
 select id into aid from public.authors where auth_user_id=p_user and status::text='APPROVED';
 if aid is null then raise exception 'AUTHOR_PROFILE_REQUIRED'; end if;
 insert into authoring.verified_author_persons(fingerprint,key_version) values(a.fingerprint,a.key_version)
  on conflict(fingerprint) do update set fingerprint=excluded.fingerprint returning id into person;
 insert into authoring.author_identity_accounts(auth_user_id,author_id,person_id,attempt_id,verified_at)
  values(p_user,aid,person,a.id,a.verified_at);
 update authoring.author_identity_attempts set status='CONSUMED',fingerprint=null where id=a.id;
 return result || jsonb_build_object('completed',true);
end $$;

-- Server maintenance only. Schedule at least hourly before enabling collection.
create or replace function public.cleanup_author_enrollment() returns bigint
language plpgsql security definer set search_path='' as $$
declare removed bigint;
begin
 delete from authoring.author_identity_attempts where status<>'CONSUMED' and created_at<=clock_timestamp()-interval '23 hours';
 get diagnostics removed=row_count; return removed;
end $$;
-- Operator-only withdrawal procedure: account access must already be disabled.
create or replace function authoring.erase_author_enrollment(p_user uuid) returns void
language plpgsql security definer set search_path='' as $$
begin
 if current_setting('webnovels.author_erasure_verified',true) is distinct from 'true' then raise exception 'Reviewed withdrawal required'; end if;
 perform 1 from auth.users u where id=p_user and ((to_jsonb(u)->>'deleted_at') is not null or banned_until>now()
  or exists(select 1 from public.authors a where a.auth_user_id=p_user and a.status::text is distinct from 'APPROVED')) for update;
 if not found then raise exception 'Disable withdrawn account before erasure'; end if;
 delete from authoring.author_identity_accounts where auth_user_id=p_user;
 delete from authoring.author_identity_attempts where auth_user_id=p_user;
