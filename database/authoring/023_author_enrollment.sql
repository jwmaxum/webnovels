create or replace function authoring.link_publication_consent() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 -- The existing publication RPC validates explicit rightsConfirmed on this exact revision/request.
 -- Older authors keep their original publication receipt; never fabricate retroactive signup consent.
 if to_jsonb(new)->>'action'='publish' and to_jsonb(new)->'payload'->'rightsConfirmed'='true'::jsonb then
  insert into authoring.publication_rights_consents(work_id,request_key,consent_attempt_id,document_id,document_version,document_hash)
   select new.work_id,new.idempotency_key,c.attempt_id,c.document_id,c.document_version,c.document_hash
   from public.works w join public.authors a on a.id=w.author_id
   join authoring.author_identity_accounts i on i.auth_user_id=a.auth_user_id and i.author_id=a.id
   join authoring.author_rights_consents c on c.attempt_id=i.attempt_id where w.id=new.work_id;
 end if;
 return new;
end $$;
revoke all on function authoring.link_publication_consent() from public,anon,authenticated,service_role;
