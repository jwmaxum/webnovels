language sql stable set search_path='' as $$
 select jsonb_build_object('id',a.id,'auth_user_id',a.auth_user_id,'purpose',a.purpose,'status',
 case when a.status in ('PENDING','VERIFIED') and a.expires_at<=clock_timestamp() then 'EXPIRED' else a.status end,
 'store_id',a.store_id,'channel_key',a.channel_key,'mode',a.mode,'pg_provider',a.pg_provider,
 'identifier_type',a.identifier_type,'key_version',a.key_version,'created_at',a.created_at,'expires_at',a.expires_at)
