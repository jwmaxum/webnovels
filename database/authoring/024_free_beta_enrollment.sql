begin;
set local lock_timeout='5s';
do $$ begin
 if current_setting('webnovels.authoring_apply_verified',true) is distinct from 'true'
 or not exists(select 1 from authoring.migrations where version='authoring-023') then
  raise exception 'Reviewed author enrollment foundation required'; end if;
end $$;

create table if not exists authoring.free_beta_settings (
 singleton boolean primary key default true check(singleton), enabled boolean not null default false
);
insert into authoring.free_beta_settings(singleton) values(true) on conflict do nothing;
create table if not exists authoring.free_beta_accounts (
 auth_user_id uuid not null references auth.users(id), kind text not null check(kind in ('reader','author')),
 profile_id text not null, rights_basis text check(rights_basis in ('OWN','LICENSED')),
 document_id text, document_version text, document_hash text, enrolled_at timestamptz not null default clock_timestamp(),
 primary key(auth_user_id,kind), unique(kind,profile_id),
 foreign key(document_id,document_version,document_hash) references authoring.enrollment_documents(id,version,hash),
 check((kind='reader' and rights_basis is null and document_id is null and document_version is null and document_hash is null)
 or (kind='author' and rights_basis is not null and document_id is not null and document_version is not null and document_hash is not null
 and document_id=case rights_basis when 'OWN' then 'copyright-own' else 'copyright-licensed' end))
);
create table if not exists authoring.free_beta_publication_consents (
 work_id bigint not null, request_key uuid not null, auth_user_id uuid not null,
 kind text not null default 'author' check(kind='author'), confirmed_at timestamptz not null default clock_timestamp(),
 primary key(work_id,request_key),
 foreign key(work_id,request_key) references authoring.publish_requests(work_id,idempotency_key),
 foreign key(auth_user_id,kind) references authoring.free_beta_accounts(auth_user_id,kind)
);
-- Access is exclusively through service-only SECURITY DEFINER RPCs; no direct table role grants.
do $$ declare t text; begin
 foreach t in array array['free_beta_settings','free_beta_accounts','free_beta_publication_consents'] loop
  execute format('alter table authoring.%I enable row level security',t);
  execute format('revoke all on authoring.%I from public,anon,authenticated,service_role',t);
 end loop;
end $$;
