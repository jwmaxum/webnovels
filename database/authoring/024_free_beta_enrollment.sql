drop trigger if exists free_beta_publication_immutable on authoring.free_beta_publication_consents;
create trigger free_beta_publication_immutable before update on authoring.free_beta_publication_consents
 for each row execute function authoring.reject_mutation();

-- Some legacy bigint reader profiles lack their own allocator. Preserve existing IDs.
do $$ declare seq text; high bigint; begin
 if exists(select 1 from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
 where a.attrelid='public.readers'::regclass and a.attname='id' and a.atttypid in ('int8'::regtype,'int4'::regtype)
 and a.attidentity='' and d.oid is null) then
  lock table public.readers in share row exclusive mode;
  alter table public.readers alter column id add generated by default as identity;
  seq:=pg_get_serial_sequence('public.readers','id');select max(id) into high from public.readers;
  if high is not null then perform setval(seq::regclass,greatest(high,1),true); end if;
 end if;
end $$;
create or replace function public.free_beta_enrollment_config() returns jsonb
language sql stable security definer set search_path='' as $$
 select jsonb_build_object('enabled',s.enabled,'mode','FREE_BETA','identityVerified',false,'documents',
  (select jsonb_agg(jsonb_build_object('id',id,'version',version,'hash',hash) order by id)
   from authoring.enrollment_documents where id in ('copyright-own','copyright-licensed')))
 from authoring.free_beta_settings s where singleton
$$;

create or replace function public.free_beta_enrollment(p_user uuid,p_action text,p_data jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_kind text; d authoring.enrollment_documents; result jsonb; pid text;
begin
 perform 1 from auth.users u where id=p_user and email_confirmed_at is not null and email is not null
  and is_anonymous is not true and (to_jsonb(u)->>'deleted_at') is null
  and (banned_until is null or banned_until<=now()) for update;
 if not found then return jsonb_build_object('error','INVALID_SESSION','status',401); end if;
 if exists(select 1 from public.authors where auth_user_id=p_user and status::text is distinct from 'APPROVED')
 or exists(select 1 from public.readers where auth_user_id=p_user and status::text is distinct from 'ACTIVE')
 or exists(select 1 from public.admin_users where auth_user_id=p_user and is_active is distinct from true) then
  return jsonb_build_object('error','ACCOUNT_INACTIVE','status',403); end if;
 if jsonb_typeof(p_data) is distinct from 'object' then return jsonb_build_object('error','INVALID_REQUEST','status',400); end if;
 perform 1 from authoring.free_beta_settings where singleton and enabled for share;
 if not found then return jsonb_build_object('error','FREE_BETA_NOT_READY','status',503); end if;
 if p_action='status' then return jsonb_build_object('completed',exists(select 1 from authoring.free_beta_accounts where auth_user_id=p_user and kind='author'),
  'existingAuthor',exists(select 1 from public.authors where auth_user_id=p_user),'mode','FREE_BETA','identityVerified',
  exists(select 1 from authoring.author_identity_accounts where auth_user_id=p_user),'attempt',null); end if;
 v_kind:=p_data->>'kind';
 if p_action is distinct from 'complete' or v_kind is null or v_kind not in ('author','reader') then
  return jsonb_build_object('error','INVALID_ACTION','status',400); end if;
 if exists(select 1 from jsonb_object_keys(p_data) k where k not in ('kind','displayName','rightsBasis','rightsAccepted','documentVersion','documentHash')) then
  return jsonb_build_object('error','FIELD_NOT_ALLOWED','status',400); end if;
 if p_data->>'displayName' is null or length(btrim(p_data->>'displayName')) not between 2 and 40 or p_data->>'displayName' ~ '[[:cntrl:]<>]' then
  return jsonb_build_object('error','INVALID_SIGNUP','status',400); end if;
 if v_kind='author' then
  if p_data->'rightsAccepted' is distinct from 'true'::jsonb or coalesce(p_data->>'rightsBasis','') not in ('OWN','LICENSED') then
   return jsonb_build_object('error','AUTHOR_CONSENT_REQUIRED','status',400); end if;
  select * into d from authoring.enrollment_documents where id=case p_data->>'rightsBasis' when 'OWN' then 'copyright-own' else 'copyright-licensed' end;
  if d.id is null or d.version is distinct from p_data->>'documentVersion' or d.hash is distinct from p_data->>'documentHash' then
   return jsonb_build_object('error','AUTHOR_CONSENT_STALE','status',409); end if;
 elsif p_data ?| array['rightsBasis','rightsAccepted','documentVersion','documentHash'] then
  return jsonb_build_object('error','FIELD_NOT_ALLOWED','status',400);
 end if;
 if exists(select 1 from authoring.free_beta_accounts where auth_user_id=p_user and free_beta_accounts.kind=v_kind) then
  return jsonb_build_object('completed',true,'created',false,'mode','FREE_BETA','identityVerified',false); end if;
 result:=authoring.create_confirmed_profile(p_user,v_kind,p_data->>'displayName');
 if v_kind='author' then select id::text into pid from public.authors where auth_user_id=p_user and status::text='APPROVED';
 else select id::text into pid from public.readers where auth_user_id=p_user and status::text='ACTIVE'; end if;
 if pid is null then raise exception 'PROFILE_REQUIRED'; end if;
 insert into authoring.free_beta_accounts(auth_user_id,kind,profile_id,rights_basis,document_id,document_version,document_hash)
 values(p_user,v_kind,pid,case when v_kind='author' then p_data->>'rightsBasis' end,d.id,d.version,d.hash);
 return result || jsonb_build_object('completed',true,'mode','FREE_BETA','identityVerified',false);
end $$;

create or replace function authoring.link_free_beta_publication_consent() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if to_jsonb(new)->>'action'='publish' and to_jsonb(new)->'payload'->'rightsConfirmed'='true'::jsonb then
  insert into authoring.free_beta_publication_consents(work_id,request_key,auth_user_id)
  select new.work_id,new.idempotency_key,c.auth_user_id from public.works w join public.authors a on a.id=w.author_id
   join authoring.free_beta_accounts c on c.auth_user_id=a.auth_user_id and c.kind='author' and c.profile_id=a.id::text
   where w.id=new.work_id;
 end if;return new;
end $$;
revoke all on function authoring.link_free_beta_publication_consent() from public,anon,authenticated,service_role;
drop trigger if exists free_beta_publication_consent_link on authoring.publish_requests;
create trigger free_beta_publication_consent_link after insert on authoring.publish_requests
 for each row execute function authoring.link_free_beta_publication_consent();
revoke all on function public.free_beta_enrollment_config(),public.free_beta_enrollment(uuid,text,jsonb) from public,anon,authenticated;
grant execute on function public.free_beta_enrollment_config(),public.free_beta_enrollment(uuid,text,jsonb) to service_role;
insert into authoring.migrations(version) values('authoring-024') on conflict do nothing;
notify pgrst,'reload schema';
commit;
