export async function rpc(db,user,action,data={}){
 return (await db.query('select public.author_enrollment($1,$2,$3) result',[user,action,data])).rows[0].result;
}
export async function consent(db,patch={}){
 const docs=(await db.query('select id,version,hash from authoring.enrollment_documents')).rows;
 const d=docs.find(d=>d.id==='copyright-own'),p=docs.find(d=>d.id==='identity-privacy');
 return {requestKey:crypto.randomUUID(),rightsBasis:'OWN',rightsAccepted:true,privacyAccepted:true,
  documentVersion:d.version,documentHash:d.hash,privacyVersion:p.version,privacyHash:p.hash,...patch};
}
export async function verified(db,user,fingerprint='a'.repeat(64),fields={}){
 const start=await rpc(db,user,'start',await consent(db,fields));
 if(start.error)throw Error(start.error);
 const attemptId=start.attempt.id;
 const result=await rpc(db,user,'verify',{attemptId,fingerprint,verifiedAt:new Date().toISOString()});
 if(result.error)throw Error(result.error);
 return attemptId;
}
